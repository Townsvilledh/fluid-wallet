// Fluid Agent Runtime — AUTONOMOUS mode.
// An AI agent creates its OWN Fluid wallet with zero human steps: it generates
// its own seed, encrypts it with a password it generates and keeps in its own
// environment, and signs its own transactions. There is no KYC (no identity
// exists), and there are no on/off-ramps in this API at all — chain only.
//
// Safety model (different from owner-assisted mode, by design):
// - The agent holds its own keys. Whoever controls the agent's machine/dir
//   controls the wallet. Fund it ONLY with what it is allowed to spend.
// - Spending caps live in the descriptor policy and are enforced in send()
//   BEFORE signing (checkAgentPolicy). Over-cap sends throw, always.
// - Sends are SERIALISED through an in-process queue and the daily spend
//   is RESERVED on disk before broadcast (audit M6): the cap check, the
//   reservation and the broadcast are atomic within the process, so two
//   concurrent send() calls can no longer both pass the daily cap on
//   the same stale spend figure. A failed broadcast releases its
//   reservation; a crash after reservation can only over-count the day
//   (the safe direction — the cap bites early, never late).
// - Seed exists in plaintext only in memory during a run; on disk it is only
//   ever the standard encrypted keystore JSON + a 0600 secret file.
//
// Usage (library):
//   import { createAgentWallet, openAgent } from "./fluid-agent.mjs";
//   const { descriptor } = await createAgentWallet({ name: "DripBot", dir: "./dripbot-wallet" });
//   const agent = await openAgent({ dir: "./dripbot-wallet" });
//   await agent.send({ network: "bsc", to: "0x…", amount: 0.01 });
//
// Usage (CLI):
//   node agent/fluid-agent.mjs create --name DripBot --dir ./dripbot-wallet
//   node agent/fluid-agent.mjs descriptor --dir ./dripbot-wallet
//   node agent/fluid-agent.mjs balance --dir ./dripbot-wallet [--network base]
//   node agent/fluid-agent.mjs send --dir ./dripbot-wallet --to 0x… --amount 0.01 [--network bsc]
import { ethers } from "ethers";
import { randomBytes } from "node:crypto";
import { mkdirSync, writeFileSync, readFileSync, existsSync, chmodSync } from "node:fs";
import { join } from "node:path";
import { NETWORKS, bitcoinAddress, getBitcoinBalance, getPrices, checkAgentPolicy, AGENT_POLICY_DEFAULTS, buildAgentDescriptor } from "../src/wallet-core.js";

const KS = "keystore.json", DESC = "descriptor.json", SECRET = ".secret", SPEND = "spend.json";
const today = () => new Date().toISOString().slice(0, 10);

/** A minimal in-process send queue: tasks run one at a time, in the
 *  order they were enqueued; a rejected task never jams the queue.
 *  Exported for tests — the serialisation is the M6 fix, not a detail. */
export function createSendQueue() {
  let tail = Promise.resolve();
  return (task) => {
    const run = tail.then(() => task());
    tail = run.then(() => {}, () => {});
    return run;
  };
}

export async function createAgentWallet({ name, dir, password, policy } = {}) {
  if (!name || String(name).trim().length < 2) throw new Error("Agent name required (2+ characters).");
  if (!dir) throw new Error("dir required — the agent's own wallet directory.");
  if (existsSync(join(dir, KS))) throw new Error("A wallet already exists in " + dir + " — refusing to overwrite an agent's seed.");
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const mnemonic = ethers.Mnemonic.entropyToPhrase(randomBytes(16)); // agent's OWN seed, generated by the agent
  const pw = password || randomBytes(24).toString("hex");             // agent-generated password
  const wallet = ethers.Wallet.fromPhrase(mnemonic);
  const keystore = await wallet.encrypt(pw);
  const keys = { evm: wallet.address, btc: bitcoinAddress(mnemonic) };
  const descriptor = buildAgentDescriptor({ name: String(name).trim(), index: 0, evm: keys.evm, btc: keys.btc, policy: { ...(policy || {}), approval: "none — autonomous; policy caps enforced in code before signing" } });
  descriptor.mode = "autonomous";            // no human in the loop
  descriptor.accountIndex = 0;               // standalone seed: its own account 0
  descriptor.seedCustody = "agent — encrypted keystore in the agent's own directory; the agent's operator funds it only with what it may spend";
  descriptor.api = "Fluid Agent Runtime (agent/fluid-agent.mjs): createAgentWallet / openAgent / send — caps enforced in code before signing.";
  writeFileSync(join(dir, KS), keystore);
  writeFileSync(join(dir, DESC), JSON.stringify(descriptor, null, 1));
  writeFileSync(join(dir, SECRET), pw + "\n", { mode: 0o600 });
  try { chmodSync(join(dir, SECRET), 0o600); } catch { /* best effort on non-POSIX */ }
  return { descriptor, dir };
}

export async function openAgent({ dir, password } = {}) {
  if (!dir || !existsSync(join(dir, KS))) throw new Error("No agent wallet in " + dir + " — create one first.");
  const descriptor = JSON.parse(readFileSync(join(dir, DESC), "utf8"));
  const pw = password || process.env.FLUID_AGENT_PASSWORD || readFileSync(join(dir, SECRET), "utf8").trim();
  const wallet = await ethers.Wallet.fromEncryptedJson(readFileSync(join(dir, KS), "utf8"), pw);
  const spendPath = join(dir, SPEND);
  const loadSpend = () => { try { return JSON.parse(readFileSync(spendPath, "utf8")); } catch { return {}; } };
  const spentToday = () => loadSpend()[today()] || 0;
  const enqueueSend = createSendQueue();
  // The send itself — only ever run inside the queue, so the sequence
  // price → cap-check → reserve → broadcast → (release on failure) is
  // atomic with respect to every other send in this process.
  const sendLocked = async ({ network = "bsc", to, amount } = {}) => {
    const net = NETWORKS[network]; if (!net) throw new Error("Unknown network: " + network);
    if (!/^0x[0-9a-fA-F]{40}$/.test(String(to || ""))) throw new Error("Invalid destination address.");
    const amt = Number(amount); if (!(amt > 0)) throw new Error("Amount must be positive.");
    const prices = await getPrices();
    const price = prices[net.symbol];
    if (!price) throw new Error(`Cannot value ${net.symbol} right now — refusing to send unpriced (safety default).`);
    const usd = amt * price;
    const gate = checkAgentPolicy(descriptor.policy, usd, spentToday());
    if (!gate.ok) throw new Error("Policy blocked: " + gate.reason);
    // RESERVE the spend on disk BEFORE broadcasting (audit M6): the
    // day's total already includes this send while it is in flight.
    const s = loadSpend(); s[today()] = spentToday() + usd;
    writeFileSync(spendPath, JSON.stringify(s));
    try {
      const p = new ethers.JsonRpcProvider(net.rpc);
      const tx = await wallet.connect(p).sendTransaction({ to, value: ethers.parseEther(String(amt)) });
      await tx.wait();
      return { hash: tx.hash, from: descriptor.keys.evm, network, amount: amt, symbol: net.symbol, usd };
    } catch (e) {
      // The send never landed — release the reservation so a transient
      // failure doesn't eat the day's cap.
      const s2 = loadSpend(); s2[today()] = Math.max(0, (s2[today()] || 0) - usd);
      writeFileSync(spendPath, JSON.stringify(s2));
      throw e;
    }
  };
  return {
    descriptor,
    addresses: () => descriptor.keys,
    async balance(network = "bsc") {
      const net = NETWORKS[network]; if (!net) throw new Error("Unknown network: " + network);
      const p = new ethers.JsonRpcProvider(net.rpc);
      return Number(ethers.formatEther(await p.getBalance(descriptor.keys.evm)));
    },
    async btcBalance() { return getBitcoinBalance(descriptor.keys.btc); },
    // Chain-native send, signed by the agent itself. Policy caps are checked
    // against live prices BEFORE signing; unpriceable or over-cap = throw.
    // Public entry point: serialised through the send queue (audit M6).
    send: (args) => enqueueSend(() => sendLocked(args)),
  };
}

// ---------- CLI ----------
if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, ...rest] = process.argv.slice(2);
  const arg = (k, d) => { const i = rest.indexOf("--" + k); return i >= 0 ? rest[i + 1] : d; };
  try {
    if (cmd === "create") {
      const out = await createAgentWallet({ name: arg("name"), dir: arg("dir"), policy: { perTxCapUsd: Number(arg("cap-tx", 50)), dailyCapUsd: Number(arg("cap-day", 200)) } });
      console.log(JSON.stringify(out.descriptor, null, 1));
    } else if (cmd === "descriptor") {
      console.log(readFileSync(join(arg("dir"), DESC), "utf8"));
    } else if (cmd === "balance") {
      const a = await openAgent({ dir: arg("dir") });
      console.log(JSON.stringify({ evm: await a.balance(arg("network", "bsc")), btc: await a.btcBalance() }));
    } else if (cmd === "send") {
      const a = await openAgent({ dir: arg("dir") });
      console.log(JSON.stringify(await a.send({ network: arg("network", "bsc"), to: arg("to"), amount: arg("amount") }), null, 1));
    } else {
      console.log("Commands: create | descriptor | balance | send  (see header of this file)");
    }
  } catch (e) { console.error("Error:", e.message); process.exit(1); }
}
