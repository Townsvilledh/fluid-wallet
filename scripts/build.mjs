// Build: bundle JS, copy pages, and produce a single-file wallet.
import { build } from "esbuild";
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { verifyLightningProvenance } from "./lightning-provenance.mjs";
mkdirSync("dist", { recursive: true });
// Lightning WASM provenance (security audit F-4.1, 2026-11-15):
// the WASM copied into dist below must match the committed
// provenance record — its own bytes AND the lightning/ source
// tree it was built from. A mismatch fails the build here, so
// dist can never silently carry a WASM that does not
// correspond to its recorded source (the in-bundle LN_WASM_PIN
// alone proved only consistency with whatever bytes shipped).
{
  const v = verifyLightningProvenance();
  if (!v.ok) { console.error("✗ Lightning provenance: " + v.reason); process.exit(1); }
  console.log("✓ Lightning WASM matches its committed provenance record (source " + v.record.sourceSha256.slice(0, 12) + "…)");
}
// Lightning node chunk FIRST: built separately and loaded lazily by
// app.js only when the Lightning panel opens. The WASM binary ships
// beside it under the exact name the chunk's init() resolves via
// import.meta.url.
await build({ entryPoints: ["src/lightning-node.js"], bundle: true, minify: true, format: "esm", outfile: "dist/lightning.chunk.js" });
// WalletConnect chunk: the Reown/WalletKit SDK, built separately and
// loaded lazily by app.js only when the WalletConnect panel opens.
await build({ entryPoints: ["src/walletconnect.js"], bundle: true, minify: true, format: "esm", outfile: "dist/walletconnect.chunk.js" });
// Arkade chunk: the Arkade SDK (wallet, VHTLC claim, offboard),
// built separately and loaded lazily by app.js only when the
// Lightning -> Bitcoin bridge tab opens.
await build({ entryPoints: ["src/arkade.js"], bundle: true, minify: true, format: "esm", outfile: "dist/arkade.chunk.js" });
// Cosmos chunk: the CosmJS + cosmjs-types SDK surface, built
// separately and loaded lazily by wallet-core on the first Cosmos
// send path (loading performance, 2026-11-16).
await build({ entryPoints: ["src/cosmos.js"], bundle: true, minify: true, format: "esm", outfile: "dist/cosmos.chunk.js" });
// Polkadot chunk: the @polkadot/* SDK surface, built separately
// and loaded lazily by wallet-core before the first Polkadot use
// (loading performance, 2026-11-16).
await build({ entryPoints: ["src/polkadot.js"], bundle: true, minify: true, format: "esm", outfile: "dist/polkadot.chunk.js" });
// Peer chunk: the @zkp2p/cash SDK (+ its @zkp2p/sdk internals and
// viem peer), built separately and loaded lazily by wallet-core
// on the first Peer cash-out path (Peer sell launch, 2026-11-16).
await build({ entryPoints: ["src/peer.js"], bundle: true, minify: true, format: "esm", outfile: "dist/peer.chunk.js" });
copyFileSync("lightning/pkg-web/fluid_lightning_bg.wasm", "dist/fluid_lightning_bg.wasm");
// Asset fingerprint pins (owner security requirement, 2026-11-10):
// the SHA-256 of the Lightning WASM and of the Lightning chunk are
// pinned INSIDE the main app bundle — app.js imports this generated
// module, verifies the chunk against its pin before importing it,
// and passes the WASM pin into the chunk, whose resumable downloader
// refuses any assembled bytes that fail the pinned hash. The pins
// are computed HERE, at build time, from the exact bytes about to be
// published — a hand-edited pin would be a stale pin, so this file
// is generated, never maintained.
{
  const wasmBytes = readFileSync("dist/fluid_lightning_bg.wasm");
  const wasmSha256 = createHash("sha256").update(wasmBytes).digest("hex");
  const chunkSha256 = createHash("sha256").update(readFileSync("dist/lightning.chunk.js")).digest("hex");
  writeFileSync("src/ln-asset-pins.generated.js",
    "// GENERATED by scripts/build.mjs — do not edit by hand.\n" +
    "// Fingerprints of the Lightning node assets, pinned in the main\n" +
    "// bundle so lazily-loaded node code is verified before it runs.\n" +
    `export const LN_WASM_PIN = { sha256: "${wasmSha256}", bytes: ${wasmBytes.length} };\n` +
    `export const LN_CHUNK_SHA256 = "${chunkSha256}";\n`);
}
// Zod dedupe (loading performance, 2026-11-16): @ton/ton is a CJS
// package whose require("zod") pulled zod's whole CJS build into
// the bundle alongside the ESM build every other consumer uses —
// two copies of the same library. The alias points the bare "zod"
// specifier at the ESM entry, so only one copy ships.
const ZOD_ESM_ENTRY = new URL("../node_modules/zod/index.js", import.meta.url).pathname;
await build({ entryPoints: ["src/app.js"], bundle: true, minify: true, outfile: "dist/app.bundle.js", external: ["./lightning.chunk.js", "./walletconnect.chunk.js", "./arkade.chunk.js", "./cosmos.chunk.js", "./polkadot.chunk.js", "./peer.chunk.js"], alias: { zod: ZOD_ESM_ENTRY } });
copyFileSync("src/index.html", "dist/index.html");
copyFileSync("tools/recovery.html", "dist/recovery.html");
copyFileSync("names.json", "dist/names.json");
copyFileSync("public/_headers", "dist/_headers");
// Agent manifest (agent kit, 2026-11-09): served at the root AND at the
// well-known path — one source file, two published copies.
mkdirSync("dist/.well-known", { recursive: true });
copyFileSync("public/fluid-agent.json", "dist/fluid-agent.json");
copyFileSync("public/fluid-agent.json", "dist/.well-known/fluid-agent.json");
// FLOSS/fund manifest (2026-11-13): the funding.json manifest lives at
// the site root, and its provenance file under .well-known — the repo
// carries the matching .well-known/funding-manifest-urls for the
// repositoryUrl provenance link inside the manifest.
copyFileSync("public/funding.json", "dist/funding.json");
copyFileSync("public/.well-known/funding-manifest-urls", "dist/.well-known/funding-manifest-urls");
// Jekyll bypass: GitHub Pages' Jekyll build never serves dot-directories
// (.well-known 404s without this). The site is fully static — nothing
// relies on Jekyll processing.
writeFileSync("dist/.nojekyll", "");
copyFileSync("public/robots.txt", "dist/robots.txt");
// Release public key (audit F-5.1, 2026-11-15): served beside
// the signed checksums so anyone can verify a release with
// scripts/verify-release.mjs. The private key never enters
// the repo — it lives only on the publishing machine.
copyFileSync("public/release-pubkey.pem", "dist/release-pubkey.pem");
copyFileSync("public/sitemap.xml", "dist/sitemap.xml");
// Donate page (2026-11-16): a plain static page on Fluid's own site —
// nobody can unlist it. Served at /donate (GitHub Pages resolves the
// extensionless path to donate.html) and /donate.html.
copyFileSync("public/donate.html", "dist/donate.html");
copyFileSync("public/og-image.png", "dist/og-image.png");
// Social card lives at a NEW filename (og-card.png, 2026-11-11): X and
// other crawlers cache card images by URL, and the old /og-image.png URL
// was still serving them the pre-rebrand purple card from cache long
// after the image at that URL had been replaced. A fresh URL forces a
// fresh fetch everywhere. og-image.png stays for the WalletConnect icon.
copyFileSync("public/og-card.png", "dist/og-card.png");
copyFileSync("public/favicon.png", "dist/favicon.png");
copyFileSync("public/CNAME", "dist/CNAME");
mkdirSync("dist/fonts", { recursive: true });
copyFileSync("public/fonts/inter-var.woff2", "dist/fonts/inter-var.woff2");
copyFileSync("public/fonts/space-grotesk-var.woff2", "dist/fonts/space-grotesk-var.woff2");
// Cache-bust the bundle: stamp dist/index.html with app.bundle.js?v=<hash> so
// every deploy is a new URL and browsers never sit on a stale bundle.
const bundleHash = createHash("sha256").update(readFileSync("dist/app.bundle.js")).digest("hex").slice(0, 10);
// Service worker: written (not copied) so its bundle-cache name
// carries THIS build's stamp — the same stamp that versions the
// bundle URL below. On activate the worker deletes every older
// stamp's cache, so a new release is fetched fresh, never stale.
writeFileSync("dist/sw.js", readFileSync("src/sw.js", "utf8").replace("__FLUID_BUILD_STAMP__", bundleHash));
const distHtml = readFileSync("dist/index.html", "utf8");
writeFileSync("dist/index.html", distHtml
  .replace('<script src="app.bundle.js"></script>', `<script src="app.bundle.js?v=${bundleHash}"></script>`)
  .replace("</head>", `<meta name="fluid-build" content="${bundleHash}"></head>`));
const html = readFileSync("src/index.html", "utf8");
const js = readFileSync("dist/app.bundle.js", "utf8");
// The single-file build inlines the bundle, so the strict CSP in
// index.html (script-src 'self') would block it. Give ONLY the single
// file a hash allowance for its exact inline script bytes: compute the
// sha256 of the precise text placed between <script>...</script> and add
// 'sha256-...' to its script-src. Any modification of the inlined script
// changes the hash and the script stops running.
const inlinedJs = js.replace(/<\/script>/g, "<\\/script>");
const singleFileHash = createHash("sha256").update(inlinedJs, "utf8").digest("base64");
const single = html
  .replace('<script src="app.bundle.js"></script>', () => "<script>" + inlinedJs + "</script>")
  .replace("script-src 'self'", `script-src 'self' 'sha256-${singleFileHash}'`);
writeFileSync("dist/fluid-wallet.html", single);
// Release checksums (audit F-5.1, 2026-11-15): sha256 of the
// release artifacts in sha256sum format. The publish step
// signs this exact file with the Ed25519 release key and
// serves checksums.txt.sig beside it — THAT is the single-
// file build's authentication story (the inlined CSP hash is
// self-referential and authenticates nothing on its own).
// Verify with scripts/verify-release.mjs.
{
  const files = ["index.html", "app.bundle.js", "fluid-wallet.html", "recovery.html",
    "fluid_lightning_bg.wasm", "lightning.chunk.js", "release-pubkey.pem"];
  const lines = files.map((f) => createHash("sha256").update(readFileSync("dist/" + f)).digest("hex") + "  " + f);
  writeFileSync("dist/checksums.txt", lines.join("\n") + "\n");
}
console.log("built dist/{index.html, app.bundle.js, recovery.html, fluid-wallet.html}", (single.length / 1024).toFixed(0) + "KB single file");
